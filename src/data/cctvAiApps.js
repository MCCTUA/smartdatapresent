// ── Helpers (used by AppDetailLayout + sticky bar + keyboard nav) ────────────
export const SLUGS = APPS.map(a => a.slug);

export function findApp(slug) {
  return APPS.find(a => a.slug === slug) || null;
}

export function neighborApps(slug) {
  const i = SLUGS.indexOf(slug);
  if (i === -1) return { prev: null, next: null, index: -1 };
  // Circular wrap — last → first, first → last (presentation friendly)
  const prev = APPS[(i - 1 + APPS.length) % APPS.length];
  const next = APPS[(i + 1) % APPS.length];
  return { prev, next, index: i };
}
